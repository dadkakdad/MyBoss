// Bundles the ES modules in js/ into one classic script (app.bundle.js) so that
// index.html works when opened straight from disk (file:// blocks <script type="module">).
// Run `npm run build` after editing anything in js/.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ORDER = ["org", "layout", "editor", "export", "sheet", "app"];

export function bundle(readModule) {
  const parts = ORDER.map((name) => {
    let src = readModule(name);
    src = src.replace(/^import\s*\{[^}]*\}\s*from\s*"[^"]+";[ \t]*\n/gm, "");
    src = src.replace(/^export\s+(?=(?:async\s+)?(?:function|const|let|class)\b)/gm, "");
    if (/^(import|export)\b/m.test(src)) throw new Error(`${name}.js: unhandled import/export left`);
    return `// ---- js/${name}.js ----\n${src}`;
  });
  return (
    "// GENERATED by build.mjs from js/*.js. Do not edit; run `npm run build`.\n" +
    `(function () {\n"use strict";\n${parts.join("\n")}\n})();\n`
  );
}

const dir = dirname(fileURLToPath(import.meta.url));
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = bundle((name) => readFileSync(join(dir, "js", `${name}.js`), "utf8"));
  writeFileSync(join(dir, "app.bundle.js"), out);
  // Stamp the script URL with a content hash so a browser never keeps serving an old bundle.
  const hash = createHash("sha1").update(out).digest("hex").slice(0, 8);
  const page = readFileSync(join(dir, "index.html"), "utf8");
  const css = createHash("sha1").update(readFileSync(join(dir, "css", "app.css"))).digest("hex").slice(0, 8);
  writeFileSync(
    join(dir, "index.html"),
    page.replace(/app\.bundle\.js(\?v=\w+)?/, `app.bundle.js?v=${hash}`).replace(/css\/app\.css(\?v=\w+)?/, `css/app.css?v=${css}`),
  );
  console.log(`Wrote app.bundle.js (${Buffer.byteLength(out)} bytes)`);
}
